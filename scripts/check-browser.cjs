// Optional integration checks. Requires Playwright and a Chromium installation.
// Start npm start first; set TEST_BASE_URL for a project-subdirectory server.
const { chromium, devices } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000/';
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.locator('.recipe-card').first().waitFor();
    assert.equal(await page.locator('.recipe-card').count(), 16);
    await page.waitForFunction(() => document.querySelector('#connection-status').textContent.includes('ready for offline'));
    assert.ok(await page.evaluate(() => navigator.serviceWorker.controller !== null));
    const manifest = await page.evaluate(async () => (await fetch(document.querySelector('link[rel=manifest]').href)).json());
    assert.equal(new URL(manifest.start_url, base).href, base);
    await page.locator('img').evaluateAll(async images => { for (const img of images) { img.loading = 'eager'; await img.decode(); } });
    await page.screenshot({ path: '/tmp/naija-kitchen-desktop.png', fullPage: true });
    await page.locator('#try-jollof').click();
    assert.equal(await page.locator('#pantry-count').textContent(), '10');
    await page.locator('[data-filter=ready]').click();
    assert.equal(await page.locator('.recipe-card').count(), 1);
    await page.locator('.recipe-card h3 button').click();
    assert.equal(await page.locator('.cooking-steps li').count(), 5);
    assert.equal(await page.locator('.detail-ingredient').count(), 10);
    await page.locator('#recipe-servings').selectOption('2');
    assert.ok((await page.locator('[data-detail="Rice"]').textContent()).includes('200 g'));
    await page.locator('#dialog-save').click();
    assert.equal(await page.locator('#dialog-save').getAttribute('aria-pressed'), 'true');
    await page.keyboard.press('Escape');
    await page.reload();
    assert.equal(await page.locator('#pantry-count').textContent(), '10');
    assert.equal(await page.locator('#saved-count').textContent(), '1');
    await page.locator('#clear-pantry').click();
    await page.locator('[data-filter=all]').click();
    await page.locator('#diet-filter').selectOption('vegan');
    assert.equal(await page.locator('.recipe-card').count(), 8);
    assert.equal(await page.locator('[data-open="9"]').count(), 0);
    await page.locator('#allergy-filters [value=peanuts]').check();
    assert.equal(await page.locator('[data-plan="5"]').count(), 0);
    await page.locator('#allergy-filters [value=gluten]').check();
    assert.equal(await page.locator('[data-plan="3"]').count(), 0);
    await page.locator('#allergy-filters [value=gluten]').uncheck();
    await page.locator('#allergy-filters [value=peanuts]').uncheck();
    await page.locator('#diet-filter').selectOption('all');
    await page.locator('[data-plan="3"]').click();
    await page.locator('[data-plan="14"]').click();
    await page.locator('#plan-servings-14').selectOption('2');
    await page.locator('#plan-servings-3').selectOption('4');
    const rice = page.locator('.shopping-item').filter({ has: page.locator('strong', { hasText: /^Rice$/ }) });
    assert.equal(await rice.count(), 1);
    assert.ok((await rice.textContent()).includes('600 g'));
    await rice.locator('input').check();
    assert.ok((await page.locator('#shopping-progress').textContent()).startsWith('1 of'));
    await page.reload();
    assert.equal(await rice.locator('input').isChecked(), true);
    await page.locator('#plan-servings-3').selectOption('8');
    assert.ok((await rice.textContent()).includes('1000 g'));
    assert.equal(await rice.locator('input').isChecked(), false);
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#download-shopping').click();
    const download = await downloadPromise;
    const content = await fs.readFile(await download.path(), 'utf8');
    assert.ok(content.includes('Rice: 1000 g'));
    await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw Error('denied'); }; });
    await page.locator('#copy-shopping').click();
    assert.ok(await page.locator('#shopping-fallback').isVisible());
    assert.ok((await page.locator('#shopping-fallback').inputValue()).includes('Rice: 1000 g'));
    await page.locator('#install-app').click();
    // In a headless browser the install guide is used instead of the native OS prompt.
    if (await page.locator('#info-dialog').isVisible()) await page.keyboard.press('Escape');
    await context.setOffline(true);
    await page.reload();
    await page.locator('.recipe-card').first().waitFor();
    assert.equal(await page.locator('.recipe-card').count(), 16);
    assert.ok((await page.locator('#connection-status').textContent()).includes('Offline'));
    await page.locator('.recipe-card h3 button').first().click();
    assert.ok(await page.locator('.cooking-steps').isVisible());
    await page.keyboard.press('Escape');
    assert.ok(await page.locator('#planned-meals').textContent().then(t => t.includes('Jollof Rice')));
    await context.setOffline(false);
    await page.locator('#ingredient-search').fill('garri');
    await page.locator('[data-ingredient="Cassava / Garri"]').click();
    await page.locator('#ingredient-search').fill('water');
    await page.locator('[data-ingredient="Water"]').click();
    await page.locator('[data-filter=ready]').click();
    assert.equal(await page.locator('.recipe-card h3').textContent(), 'Eba (Garri Swallow)');
    await page.locator('#ingredient-search').fill('');
    for (const id of ['1', '2', '3', '4', '5']) {
      await page.locator(`[data-category="${id}"]`).click();
      await page.locator('#select-category').click();
    }
    assert.equal(await page.locator('#ready-count').textContent(), '16');
    await page.locator('[data-category="1"]').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('[data-category="2"]').getAttribute('aria-selected'), 'true');
    await page.locator('#photo-credits').click();
    assert.ok(await page.getByRole('heading', { name: 'From our kitchen, with credit.' }).isVisible());
    await page.keyboard.press('Escape');
    const accessibility = await (await context.newCDPSession(page)).send('Accessibility.getFullAXTree');
    assert.ok(accessibility.nodes.some(node => node.role?.value === 'tablist' && node.name?.value === 'Ingredient categories'));
    assert.ok(accessibility.nodes.some(node => node.role?.value === 'heading' && node.name?.value === 'From kitchen to market.'));
    assert.deepEqual(errors, []);
    console.log('PASS: desktop, measured recipes, serving scaling, diet/allergy filters, combined quantities, checklist persistence, downloads, clipboard fallback, offline reload and recipe details, keyboard, credits.');
    await context.close();
    const mobile = await browser.newContext({ ...devices['Pixel 7'] });
    const phone = await mobile.newPage();
    await phone.goto(base);
    await phone.locator('.recipe-card').first().waitFor();
    for (const width of [320, 390, 412, 768]) {
      await phone.setViewportSize({ width, height: 900 });
      assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}px`);
    }
    await phone.setViewportSize({ width: 390, height: 844 });
    await phone.locator('img').evaluateAll(async images => { for (const img of images) { img.loading = 'eager'; await img.decode(); } });
    await phone.screenshot({ path: '/tmp/naija-kitchen-mobile.png', fullPage: true });
    await phone.locator('.recipe-card h3 button').first().click();
    assert.ok(await phone.getByRole('heading', { name: 'Let’s cook', exact: true }).isVisible());
    assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await phone.keyboard.press('Escape');
    const targets = await phone.locator('.ingredient, .save-button, .category-tab').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height));
    assert.ok(targets.every(height => height >= 44));
    console.log('PASS: Android browser emulation, mobile recipe dialog, 320/390/412/768px layouts, 44px primary touch targets. Physical Android hardware not tested.');
    await mobile.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
